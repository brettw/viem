//!
//! Each file in `tests/` used to be its own crate and executable, and each of
//! those linked the whole core library and the Tree-sitter grammars. Keeping
//! the files as modules of one crate links them once. Cargo only builds
//! top-level files in `tests/` as separate binaries, so the modules live in
//! this subdirectory. Run one file's tests with a module filter, for example
//! `cargo test --test all hard_line_reflow::`.

