#!/usr/bin/env python3
"""Regenerate builtin metadata from a local copy of Vim 9.2.0000 evalfunc.c.

No build or test downloads upstream files. The committed metadata carries Vim's
license; this maintainer tool verifies the exact source before extracting data.
"""
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE_SHA256 = "666b3d509ea9a853ae7158133ae94e32ed97823be6af318b69cc9f59a8bb9ea0"


def variant(name):
    return "".join(part.capitalize() for part in name.split("_"))


def generate(source):
    arrays = {
        name: [rule.strip() for rule in body.split(",") if rule.strip() != "NULL"]
        for name, body in re.findall(r"static argcheck_T (\w+)\[\] = \{([^}]+)\};", source)
    }
    entries = re.findall(
        r'\{"(\w+)",\s*(\d+),\s*(\d+|VARGS),\s*([^,]+),\s*(\w+),\s*(ret_\w+),',
        re.sub(r"//[^\n]*", "", source.split("static const funcentry_T global_functions[] =", 1)[1]),
    )
    assert len(entries) > 500 and [e[0] for e in entries] == sorted(e[0] for e in entries)
    rules = sorted({rule for e in entries if e[4] != "NULL" for rule in arrays[e[4]]})
    returns = sorted({e[5] for e in entries})
    out = [
        "// Generated by scripts/update-vim-builtin-signatures.py. Do not edit.",
        "// Metadata derived from Vim v9.2.0000 src/evalfunc.c by Bram Moolenaar",
        "// and contributors, under the Vim license: docs/licenses/LICENSE_vim.txt.",
        f"// Upstream SHA-256: {SOURCE_SHA256}",
        "#[derive(Clone, Copy, Debug)]", "enum Rule {",
        *[f"    {variant(r)}," for r in rules], "}",
        "#[derive(Clone, Copy, Debug)]", "enum Return {",
        *[f"    {variant(r.removeprefix('ret_'))}," for r in returns], "}",
        "static SIGNATURES: &[Signature] = &[",
    ]
    for name, low, high, flags, checks, result in entries:
        method = re.search(r"FEARG_(\d)", flags)
        method = f"Some({int(method[1]) - 1})" if method else "None"
        checks = ", ".join(f"Rule::{variant(r)}" for r in arrays.get(checks, []))
        high = "usize::MAX" if high == "VARGS" else high
        out.append(f'    Signature {{ name: "{name}", min: {low}, max: {high}, method: {method}, meta: {str("FE_X" in flags).lower()}, args: &[{checks}], result: Return::{variant(result.removeprefix("ret_"))} }},')
    out += ["];", ""]
    return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: update-vim-builtin-signatures.py /path/to/vim/src/evalfunc.c")
    source = Path(sys.argv[1]).read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        sys.exit("source hash mismatch: expected Vim v9.2.0000 src/evalfunc.c")
    (ROOT / "src/core/vimscript/builtins/signatures_data.rs").write_text(generate(source.decode()))
