#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn filename_rules_are_sorted_unique_and_reference_bundled_languages() {
        let languages = crate::document::syntax::languages::supported_languages();
        for rules in [NAMES, SUFFIXES, EXTENSIONS, CASE_INSENSITIVE_EXTENSIONS] {
            assert!(rules.windows(2).all(|pair| pair[0].0 < pair[1].0), "rules must be sorted and unique");
            for (pattern, language) in rules {
                assert!(!pattern.is_empty() && pattern.len() <= 128 && !pattern.contains(['/', '\\']));
                assert!(languages.iter().any(|candidate| candidate.id == *language), "{pattern}: {language} is not bundled");
            }
        }
        for (extension, _) in CASE_INSENSITIVE_EXTENSIONS {
            assert!(!EXTENSIONS.iter().any(|(other, _)| extension.eq_ignore_ascii_case(other)), "overlapping extension: {extension}");
        }
    }
}
