//! Curated portable filename rules, audited against Vim 9.2's filetype.vim
//! and autoload/dist/ft.vim and Viem's bundled syntax catalogue. See PROFILE.md.
//! These are data-only rules: startup never loads or executes Vim file detection.
//!
//! Keep these tables in sync when the Vim inventory, Tree-sitter packages or
//! language catalogue changes; follow PROFILE.md's language maintenance checklist.
//! Audit real extensions/basenames, use canonical catalogue IDs, and add detection
//! and opening tests. Document ambiguous omissions instead of guessing. Syntax
//! file stems and Tree-sitter query names are not automatic extension mappings.

fn exact(rules: &[(&str, &'static str)], value: &str) -> Option<&'static str> {
    rules.binary_search_by_key(&value, |(key, _)| *key).ok().map(|index| rules[index].1)
}

pub(super) fn language(base: &str, extension: &str) -> Option<&'static str> {
    if let Some(language) = exact(NAMES, base) { return Some(language); }
    // Compound suffixes precede the final extension (e.g. project.csproj.user).
    if let Some((_, language)) = SUFFIXES.iter().find(|(suffix, _)| base.ends_with(suffix)) {
        return Some(language);
    }
    if let Some(language) = exact(EXTENSIONS, extension) { return Some(language); }
    // Fold only designated extensions. In particular .c/.C and .h/.H differ.
    if let Some((_, language)) = CASE_INSENSITIVE_EXTENSIONS.iter().find(|(suffix, _)| extension.eq_ignore_ascii_case(suffix)) {
        return Some(language);
    }
    if base.eq_ignore_ascii_case("justfile") || extension.eq_ignore_ascii_case("justfile") {
        return Some("just");
    }
    // Broad filename variants lose to a recognized extension, as in Vim.
    if base.starts_with("Dockerfile.") || base.starts_with("Containerfile.") { return Some("dockerfile"); }
    if base.starts_with("Makefile.") || base.starts_with("makefile.") || base.starts_with("GNUmakefile.") { return Some("make"); }
    // Vim's shell-rc wildcard rules are deliberately lower priority than
    // recognized suffixes. Compressed artifacts must retain Text fallback.
    if !matches!(extension, "gz" | "bz2" | "Z" | "xz" | "zip" | "tgz") {
        if [".zsh", ".zlog", ".zcompdump", "zsh", "zlog"].iter().any(|prefix| base.starts_with(prefix)) { return Some("zsh"); }
        if [".bashrc", ".bash_profile", ".bash-profile", ".bash_logout", ".bash-logout", ".bash_aliases", ".bash-aliases", "bash-fc.", "bash-fc-"].iter().any(|prefix| base.starts_with(prefix)) { return Some("bash"); }
        if base.starts_with(".kshrc") { return Some("ksh"); }
        if base.starts_with(".envrc.") { return Some("sh"); }
        if base.starts_with(".profile") { return Some("sh"); }
        if base.starts_with(".tcshrc") { return Some("tcsh"); }
        if base.starts_with(".cshrc") || base.starts_with(".login") { return Some("csh"); }
    }
    base.contains("vimrc").then_some("vim")
}

