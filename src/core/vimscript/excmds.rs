/// Commands where Ctrl-V escapes the next character and `\|` is kept as a
/// literal bar: mappings, abbreviations and menus.
pub fn is_map_like(name: &str) -> bool {
    const MAPS: &[&str] = &[
        "map", "nmap", "vmap", "xmap", "smap", "omap", "imap", "lmap", "cmap", "tmap",
        "noremap", "nnoremap", "vnoremap", "xnoremap", "snoremap", "onoremap", "inoremap",
        "lnoremap", "cnoremap", "tnoremap", "unmap", "nunmap", "vunmap", "xunmap", "sunmap",
        "ounmap", "iunmap", "lunmap", "cunmap", "tunmap", "mapclear", "nmapclear", "vmapclear",
        "xmapclear", "smapclear", "omapclear", "imapclear", "lmapclear", "cmapclear", "tmapclear",
        "abbreviate", "noreabbrev", "iabbrev", "inoreabbrev", "cabbrev", "cnoreabbrev",
        "unabbreviate", "iunabbrev", "cunabbrev", "abclear", "iabclear", "cabclear",
    ];
    MAPS.contains(&name) || name.ends_with("menu") || name.ends_with("menu!") || name == "unmenu"
}

pub fn sees_bar(name: &str) -> bool {
    SEES_BAR.contains(&name)
}

pub fn allows_comment(name: &str) -> bool {
    !NO_COMMENT.contains(&name) && !is_map_like(name)
}

/// Resolve a possibly abbreviated command name.
pub fn lookup(name: &str) -> Option<&'static str> {
    if name.is_empty() {
        return None;
    }
    let mut best: Option<(&'static str, usize)> = None;
    for &(full, minimum) in COMMANDS {
        if full == name {
            return Some(full);
        }
        if name.len() >= minimum && full.starts_with(name) {
            // Prefer the command whose required prefix is longest, which is
            // how Vim's table ordering disambiguates.
            if best.is_none_or(|(_, best_min)| minimum > best_min) {
                best = Some((full, minimum));
            }
        }
    }
    best.map(|(full, _)| full)
}

